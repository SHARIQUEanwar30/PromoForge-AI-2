"""Generalization test: run the SAME code on different synthetic stories in different formats.

Writes docs/generalization_test.md from REAL runs (nothing typed by hand). Uses only synthetic stories, so the
report is safe for a public repo.

Run:  python tools/run_generalization.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from promoforge.llm_provider import Settings  # noqa: E402
from promoforge.pipeline import run_pipeline  # noqa: E402

STORIES = [
    ("story_labelled", "period romance / revenge", "labelled blocks WITH timestamps"),
    ("story_inline", "sci-fi thriller", "inline [mm:ss - mm:ss] lines WITH timestamps"),
    ("story_fountain", "office revenge comedy", "Fountain screenplay with NO timestamps"),
]


def main() -> None:
    if not (ROOT / "sample_data" / "story_labelled").exists():
        import runpy
        runpy.run_path(str(ROOT / "tools" / "make_sample_data.py"), run_name="__main__")
    lines = ["# Generalization test", "",
             "The same code, with no story-specific settings, run on three synthetic stories (invented for this repo) "
             "that differ in genre and in file format. Generated by `tools/run_generalization.py` from real runs, rules-only mode.", ""]
    lines += ["| Story | Genre | Format detected | Episodes | Beats | Timing | Promos | Pass Python validation | Confidence (H/M/L) |",
              "|---|---|---|---|---|---|---|---|---|"]
    details = []
    for name, genre, fmt in STORIES:
        res = run_pipeline(input_path=ROOT / "sample_data" / name, settings=Settings(provider="none"), top_n=6)
        r = res.report
        ok = sum(p.validation.ok for p in res.promos)
        conf = {c: sum(1 for p in res.promos if p.confidence == c) for c in ("high", "medium", "low")}
        lines.append(f"| {name} | {genre} | {', '.join(r['input']['formats'])} | {r['input']['episodes']} | {r['input']['total_beats']} | "
                     f"{'ESTIMATED' if r['input']['timing_estimated'] else 'from source'} | {len(res.promos)} | {ok}/{len(res.promos)} | "
                     f"{conf['high']}/{conf['medium']}/{conf['low']} |")
        top = res.promos[0]
        details.append((name, fmt, top, res))
    lines += ["", "## Top pick per story", ""]
    for name, fmt, top, res in details:
        seg = ", ".join(f"E{s.episode} {s.start_ts}-{s.end_ts}" for s in top.segments)
        lines += [f"### {name} ({fmt})",
                  f"- Rank 1: {seg}  ({top.duration:.1f}s), confidence **{top.confidence}**",
                  f"- Hook: {top.hook}", f"- Cliffhanger: {top.cliffhanger}",
                  f"- Standalone risks: {'; '.join(top.standalone_risks) or 'none flagged'}", ""]
    lines += ["## What this shows and what it does not", "",
              "- The parsers and the scoring ran unchanged on three layouts and three genres; every promo passed Python validation.",
              "- For the no-timestamp story, times are ESTIMATED from word counts, every promo is marked low confidence and carries a warning. "
              "Real timestamps must be supplied before anyone cuts video from those numbers.",
              "- It does NOT show that the picks are good: these stories are tiny and written by the tool's author. "
              "Quality needs human labels (use Keep / Skip in the app, then the `evaluate` command).", ""]
    out = ROOT / "docs" / "generalization_test.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:12]))
    print("written", out)


if __name__ == "__main__":
    main()
